    fun savingsAndInvestmentAllocations(settings: SettingsEntity): MetricInfo {
        val dcaBase = FinancialEngine.baseInvestMonthly(settings)
        val reserveCurrent = settings.emergencyReserveCurrent.coerceAtLeast(0.0)
        val reserveTarget = FinancialEngine.effectiveEmergencyReserveTarget(settings)
        val reserveContrib = FinancialEngine.monthlyEmergencyReserveContribution(settings)
        val isManual = settings.emergencyReserveMonthlyOverride.isFinite() && settings.emergencyReserveMonthlyOverride >= 0.0
        val reserveRule = if (isManual) {
            "Manual Monthly Reserve Override: ${fmtCZK(reserveContrib)}/month"
        } else if (reserveCurrent < reserveTarget) {
            "Emergency Reserve = (${fmtCZK(reserveTarget)} target − ${fmtCZK(reserveCurrent)} current) ÷ 24 months = ${fmtCZK(reserveContrib)}/month"
        } else {
            "Emergency Reserve = 0 Kč/month (100% of ${fmtCZK(reserveTarget)} target funded)"
        }
        return MetricInfo(
            title = "Savings & Investment Allocations",
            category = "Monthly Capital Deployment",
            formulaOrRule = "DCA Investments (${fmtCZK(dcaBase)}) + $reserveRule",
            explanation = if (isManual) {
                "Shows your recurring monthly investment streams (Portu ETF, DIP, DPS, Employer Match) plus your manually configured monthly emergency reserve contribution (${fmtCZK(reserveContrib)}/month)."
            } else {
                "Shows your recurring monthly investment streams (Portu ETF, DIP, DPS, Employer Match) plus an automatic 24-month emergency reserve catch-up whenever your current reserve (${fmtCZK(reserveCurrent)}) is below your ${settings.emergencyReserveMode} target (${fmtCZK(reserveTarget)})."
            },
            practicalImplication = "Tap Edit on the Savings & Investment Allocations card to switch Emergency Reserve Contribution between Auto (24-month target catch-up) and an explicit Manual monthly amount (including 0 Kč).",
            accentColor = BrandTeal
        )
    }

